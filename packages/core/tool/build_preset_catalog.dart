import 'dart:convert';
import 'dart:io';

import 'package:args/args.dart';
import 'package:pagestage_core/src/preset_catalog.dart';

/// Builds the bundled catalog offline from reviewed public metadata snapshots.
Future<void> main(List<String> arguments) async {
  final args = (ArgParser()..addOption('minimax-metadata')).parse(arguments);
  final directory = File.fromUri(Platform.script).parent;
  final presets = <Map<String, Object?>>[];
  for (final provider in ['minimax', 'bailian']) {
    final file = File('${directory.path}/voice_sources/$provider.json');
    final source =
        jsonDecode(await file.readAsString()) as Map<String, dynamic>;
    if (provider == 'minimax' && args['minimax-metadata'] != null) {
      final metadata =
          jsonDecode(
                await File(args['minimax-metadata'] as String).readAsString(),
              )
              as Map;
      final voices = {
        for (final row in metadata['system_voice'] as List)
          (row as Map)['voice_id'] as String: row,
      };
      for (final row in source['voices'] as List) {
        final voice = voices[row['id']];
        row.remove('apiName');
        row.remove('apiDescription');
        row['apiMetadataAvailable'] = voice != null;
        if (voice != null) {
          row['apiName'] = voice['voice_name'] as String;
          row['apiDescription'] = (voice['description'] as List).cast<String>();
        }
      }
      source['metadataSourceUrl'] = metadata['sourceUrl'] as String;
      source['metadataRetrievedAt'] = metadata['retrievedAt'] as String;
      await file.writeAsString('${_encoder.convert(source)}\n');
    }
    for (final row in source['voices'] as List) {
      presets.add(buildPreset(provider, source, row as Map<String, dynamic>));
    }
  }
  final keys = presets.map((row) => '${row['provider']}:${row['id']}').toSet();
  if (keys.length != presets.length) throw StateError('Duplicate presets.');
  final output = File('${directory.path}/../lib/src/preset_catalog_data.dart');
  await output.writeAsString(
    "// Generated by tool/build_preset_catalog.dart from tool/voice_sources/.\n"
    "// See docs/cli-casting.md for sources and tag limitations.\n"
    "const presetCatalogJson = r'''\n${_encoder.convert(presets)}\n''';\n",
  );
  stdout.writeln('Built ${presets.length} presets offline.');
}

const _encoder = JsonEncoder.withIndent('  ');

Map<String, Object?> buildPreset(
  String provider,
  Map<String, dynamic> source,
  Map<String, dynamic> row,
) {
  final apiDescription = (row['apiDescription'] as List?)?.cast<String>();
  final description =
      apiDescription?.join('；') ?? row['description'] as String? ?? '';
  final label = row['apiName'] as String? ?? row['providerLabel'] as String;
  final text = '$label $description';
  // Prefer detailed descriptions over shorter names (e.g. Gentle Senior is
  // described as a young adult 学姐, not an elderly voice).
  final descriptionGender = inferGender(description);
  final nameGender = inferGender(label);
  final gender =
      row['gender'] as String? ??
      (descriptionGender != 'unknown'
          ? descriptionGender
          : nameGender != 'unknown'
          ? nameGender
          : inferGender(
              (row['id'] as String).replaceAll(RegExp(r'[_-]'), ' '),
            ));
  final descriptionAge = inferAge(description);
  final age = descriptionAge != 'unknown' ? descriptionAge : inferAge(label);
  final useCases = row['useCases'] as String? ?? '';
  final review = row['narratorReview'] as String? ?? 'notReviewed';
  final narrator =
      review == 'approved' ||
      RegExp(
        r'narrat|storyteller|audiobook|旁白|有声书|讲故事|讲述故事|故事讲述',
        caseSensitive: false,
      ).hasMatch('$text $useCases');
  final origin = apiDescription != null
      ? 'provider API description/name'
      : provider == 'bailian'
      ? 'provider voice table'
      : 'provider voice name';
  final tableSource = row['sourceUrl'] ?? source['sourceUrl'];
  return {
    'provider': provider,
    'model': source['model'],
    'id': row['id'],
    'languages': row['languages'],
    'gender': gender,
    'ageGroup': age,
    'providerLabel': label,
    'description': description,
    'useCases': useCases,
    'styles': voiceStyleTags(text),
    'narratorCandidate': narrator,
    'narratorReview': review,
    'regions': row['regions'] ?? ['provider-configured'],
    'sourceUrl': apiDescription != null
        ? source['metadataSourceUrl']
        : tableSource,
    'checkedAt': source['metadataRetrievedAt'] ?? source['checkedAt'],
    'tagProvenance': {
      'languages': 'provider voice table: $tableSource',
      'gender': gender == 'unknown'
          ? 'unknown: not specified in official metadata'
          : row['gender'] != null
          ? 'provider voice table: explicit gender'
          : descriptionGender != 'unknown' || nameGender != 'unknown'
          ? '$origin: gender wording mapped to tag; not auditioned'
          : 'provider voice ID: gender wording mapped to tag; not auditioned',
      'ageGroup': age == 'unknown'
          ? 'unknown: not specified in official metadata'
          : '$origin: wording mapped to age band; not auditioned',
      'styles': '$origin: bilingual delivery terms; not auditioned',
      'narratorCandidate': review == 'approved'
          ? 'manual listening review: ${row['reviewNotes']}'
          : narrator
          ? '$origin: narration or audiobook wording; not auditioned'
          : 'unknown: no narration use documented',
    },
    'metadataGaps': [
      if (provider == 'minimax' && row['apiMetadataAvailable'] == false)
        'apiMetadata',
      if (gender == 'unknown') 'gender',
      if (age == 'unknown') 'ageGroup',
      if (description.isEmpty) 'description',
      if (voiceStyleTags(text).isEmpty) 'styles',
      if (review != 'approved') 'narratorListeningReview',
    ],
  };
}

String inferGender(String text) {
  final female = RegExp(
    r'\b(female|woman|women|girl|lady|queen|aunt|auntie|antie|sister|mother|miss|hostess)\b|女|姐姐|学姐|御姐|阿姨|奶奶|大婶|闺蜜|妹妹|学妹|萌妹|空姐',
    caseSensitive: false,
  ).hasMatch(text);
  final male = RegExp(
    r'\b(male|man|men|boy|gentleman|guy|bloke|uncle|brother|father)\b|男|大叔|三叔|老爷|爷爷|大爷|弟弟|学弟|学长|少爷|竹马|小哥|绅士',
    caseSensitive: false,
  ).hasMatch(text);
  return female == male
      ? 'unknown'
      : female
      ? 'female'
      : 'male';
}

String inferAge(String text) {
  // Explicit life stages take precedence over broad stylistic adjectives.
  for (final entry in <String, String>{
    'child': r'\b(child|kid|toddler)\b|男童|女童|童声',
    'teen': r'\b(teen|teenager|teenage)\b|少年|少女',
    'senior': r'\b(elder|elderly|senior|old)\b|老年|老人|爷爷|奶奶',
    'youngAdult': r'\b(young|youth|youthful)\b|青年|年轻|轻熟|大男孩',
    'middleAged': r'\b(middle[ -]aged|mature)\b|中年|成熟',
  }.entries) {
    if (RegExp(entry.value, caseSensitive: false).hasMatch(text)) {
      return entry.key;
    }
  }
  return 'unknown';
}
